"""Offline, scheduling-gated Hotel application Pods; no execution authority.

The original support Deployments stay at zero replicas. These standalone Pods
use the guarded image and its explicit run/dataset identity, and never restart.
Existing Services and NetworkPolicies select their audited component labels.
No Kubernetes mutation, initialization replay, or application release occurs
here. A live controller must verify initialization and all ownership/continuity
evidence, durably consume dispatch latches, and own cleanup before releasing
any scheduling gate. Saved manifests cannot substitute for those checks.
"""

from __future__ import annotations

from dataclasses import dataclass, field
import hashlib
import json
from typing import Any

from .deathstarbench_hotel_runtime import validate_guarded_hotel_runtime_plan


STAGE_REVISION = 'hotel-guarded-application-stage-candidate-v1'
STAGE_SCHEMA = 'hotel-guarded-application-stage-v1'
SCHEDULING_GATE = 'deathstarbench.io/hotel-application-controller'
STARTUP_GROUPS = (
    ('attractions', 'geo', 'profile', 'rate', 'recommendation', 'reservation', 'review', 'user'),
    ('search',), ('frontend',),
)
COMPONENTS = tuple(sorted(name for group in STARTUP_GROUPS for name in group))


class GuardedHotelApplicationStageError(ValueError):
    """Application staging would cross its exact guarded runtime contract."""


def _canonical(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':'), allow_nan=False) + '\n'


def _fingerprint(value):
    return 'sha256:' + hashlib.sha256(_canonical(value).encode()).hexdigest()


def _checked_plan(plan):
    try:
        checked = validate_guarded_hotel_runtime_plan(plan)
        # Re-derivation checks values; the original also needs strict flag
        # checks because integer aliases compare equal to Boolean fields.
        plan.__post_init__()
        return checked
    except (ValueError, TypeError, AttributeError, KeyError) as exc:
        raise GuardedHotelApplicationStageError('An exact guarded Hotel runtime plan is required.') from exc


def _derive(plan):
    deployments = {
        item['metadata']['name']: item
        for item in json.loads(plan.support_stage.canonical_json)['items']
        if item['kind'] == 'Deployment' and item['metadata']['name'] in COMPONENTS
    }
    if tuple(sorted(deployments)) != COMPONENTS:
        raise GuardedHotelApplicationStageError('The exact ten paused Hotel applications are required.')
    pods = []
    consul_services = {}
    for component in COMPONENTS:
        deployment = deployments[component]
        if deployment['spec']['replicas'] != 0:
            raise GuardedHotelApplicationStageError('The original Hotel applications must remain paused.')
        template = deployment['spec']['template']
        original = template['spec']['containers'][0]
        labels = dict(template['metadata']['labels'])
        # ReplicaSets generated by the paused Deployments additionally select
        # pod-template-hash. Do not carry that label or any controller owner.
        # Live admission must reject foreign/adopting controllers regardless.
        labels.update({
            'deathstarbench.io/candidate-run-id': plan.run_id,
            'deathstarbench.io/hotel-application-stage': 'guarded-v1',
            'deathstarbench.io/hotel-initialization-attempt': plan.initialization_attempt_id,
        })
        environment = {item['name']: item['value'] for item in original['env']}
        environment.update(plan.initialization_environment())
        container = {
            'name': component, 'image': plan.application_image,
            'imagePullPolicy': 'Always', 'workingDir': '/workspace',
            'command': list(original['command']),
            'env': [{'name': key, 'value': value} for key, value in sorted(environment.items())],
            'ports': original['ports'], 'readinessProbe': original['readinessProbe'],
            'securityContext': {'allowPrivilegeEscalation': False, 'readOnlyRootFilesystem': True,
                                'capabilities': {'drop': ['ALL']}},
            'resources': {'requests': {'cpu': '100m', 'memory': '64Mi'},
                          'limits': {'cpu': '1', 'memory': '512Mi'}},
        }
        if component != 'frontend':
            consul_services[component] = {
                'name': 'srv-' + component, 'port': original['ports'][0]['containerPort'],
            }
        pods.append({
            'apiVersion': 'v1', 'kind': 'Pod',
            'metadata': {
                'name': 'hotel-app-' + component + '-' + plan.initialization_attempt_id.replace('-', ''),
                'namespace': plan.namespace, 'labels': labels,
                'annotations': {
                    'deathstarbench.io/candidate-run-id': plan.run_id,
                    'deathstarbench.io/hotel-runtime-fingerprint': plan.fingerprint,
                    'deathstarbench.io/hotel-application-stage-revision': STAGE_REVISION,
                    'deathstarbench.io/hotel-initialization-attempt': plan.initialization_attempt_id,
                    'deathstarbench.io/application-start-allowed': 'false',
                },
            },
            'spec': {
                'schedulingGates': [{'name': SCHEDULING_GATE}],
                'restartPolicy': 'Never', 'activeDeadlineSeconds': 900,
                'terminationGracePeriodSeconds': 10,
                'automountServiceAccountToken': False, 'enableServiceLinks': False,
                'dnsPolicy': 'ClusterFirst', 'schedulerName': 'default-scheduler',
                'hostNetwork': False, 'hostPID': False, 'hostIPC': False,
                'shareProcessNamespace': False,
                'nodeSelector': dict(template['spec']['nodeSelector']),
                'securityContext': {'runAsNonRoot': True, 'runAsUser': 65532, 'runAsGroup': 65532,
                                    'seccompProfile': {'type': 'RuntimeDefault'}},
                'containers': [container],
            },
        })

    identity = {
        'schema_version': 1, 'candidate_schema': STAGE_SCHEMA, 'revision': STAGE_REVISION,
        'candidate_only': True,
        **{name: False for name in ('application_start_allowed', 'initialization_verified',
                                   'runtime_qualified', 'measurement_qualified', 'cloud_qualified',
                                   'public_release', 'released')},
        'run_id': plan.run_id, 'namespace': plan.namespace, 'plan_fingerprint': plan.fingerprint,
        'initialization_attempt_id': plan.initialization_attempt_id,
        'application_image': plan.application_image,
        'application_architecture': plan.application_architecture,
        'support_stage_fingerprint': plan.support_stage.fingerprint,
        'scope': 'offline-gated-application-pods-only', 'execution_authority': 'none',
        'recovery': 'cleanup-only-no-restart-or-replay',
        'scheduling_gate': SCHEDULING_GATE,
        'components': list(COMPONENTS), 'startup_groups': [list(group) for group in STARTUP_GROUPS],
        'pod_names': {pod['spec']['containers'][0]['name']: pod['metadata']['name'] for pod in pods},
        'consul_services': consul_services,
        'readiness_scope': 'tcp-listener-only-not-semantic-readiness',
        'required_live_checks': [
            'fresh-guarded-artifact-and-anonymous-image-access',
            'held-run-lease-and-exact-cloud-cluster-namespace-storage-support-continuity',
            'same-attempt-successful-initializer-and-global-verifier',
            'original-application-deployments-remain-zero-and-no-adopting-controllers',
            'exact-admitted-pod-spec-and-uid-before-single-use-dispatch',
            'unchanged-application-container-identities-with-zero-restarts',
            'consul-registrations-match-nine-observed-pod-addresses-and-ports',
            'semantic-login-and-reservation-validation-after-startup',
            'exact-cleanup-and-independent-resource-absence',
        ],
    }
    fingerprint = _fingerprint(identity)
    for pod in pods:
        pod['metadata']['annotations']['deathstarbench.io/hotel-application-stage-fingerprint'] = fingerprint
    payload = _canonical({'apiVersion': 'v1', 'kind': 'List', 'items': pods})
    rendered_hash = 'sha256:' + hashlib.sha256(payload.encode()).hexdigest()
    return {
        'run_id': plan.run_id, 'namespace': plan.namespace, 'plan_fingerprint': plan.fingerprint,
        'components': COMPONENTS, 'startup_groups': STARTUP_GROUPS, 'fingerprint': fingerprint,
        'canonical_json': payload, 'rendered_manifest_sha256': rendered_hash,
        '_metadata_json': _canonical({**identity, 'fingerprint': fingerprint,
                                     'rendered_manifest_sha256': rendered_hash}),
    }


@dataclass(frozen=True, slots=True)
class GuardedHotelApplicationStage:
    plan: Any = field(repr=False)
    run_id: str
    namespace: str
    plan_fingerprint: str
    components: tuple[str, ...]
    startup_groups: tuple[tuple[str, ...], ...]
    fingerprint: str
    canonical_json: str
    rendered_manifest_sha256: str
    _metadata_json: str = field(repr=False)
    candidate_only: bool = field(init=False, default=True)
    application_start_allowed: bool = field(init=False, default=False)
    released: bool = field(init=False, default=False)

    def __post_init__(self):
        checked = _checked_plan(self.plan)
        if (self.candidate_only is not True or self.application_start_allowed is not False
                or self.released is not False):
            raise GuardedHotelApplicationStageError('Offline application staging cannot authorize startup.')
        for name, value in _derive(checked).items():
            if type(getattr(self, name)) is not type(value) or getattr(self, name) != value:
                raise GuardedHotelApplicationStageError('Application stage differs from exact derivation: ' + name)
        object.__setattr__(self, 'plan', checked)

    def metadata(self) -> dict:
        return json.loads(self._metadata_json)

    def pod(self, component: str) -> dict:
        if type(component) is not str or component not in self.components:
            raise GuardedHotelApplicationStageError('An exact audited Hotel application component is required.')
        return next(item for item in json.loads(self.canonical_json)['items']
                    if item['spec']['containers'][0]['name'] == component)


def build_guarded_hotel_application_stage(plan) -> GuardedHotelApplicationStage:
    """Derive ten blocked application Pods, without network or execution calls."""
    checked = _checked_plan(plan)
    return GuardedHotelApplicationStage(plan=checked, **_derive(checked))


def validate_guarded_hotel_application_stage(plan, stage) -> GuardedHotelApplicationStage:
    expected = build_guarded_hotel_application_stage(plan)
    if type(stage) is not GuardedHotelApplicationStage or stage != expected:
        raise GuardedHotelApplicationStageError('Guarded application stage is crossed or stale.')
    # Equality alone accepts Python's 0/False and 1/True aliases if a caller
    # bypassed frozen fields. Recheck exact field types and closed flags too.
    stage.__post_init__()
    return expected
